async function main() {
  const office = await prisma.user.findUnique({
    where: { email: OFFICE_EMAIL },
    select: { id: true, email: true, role: true },
  });

  if (!office) {
    throw new Error(
      `no account for ${OFFICE_EMAIL} — run prisma/seed-pattara.ts first`,
    );
  }
  if (office.role !== "PATTARA") {
    throw new Error(`${OFFICE_EMAIL} is ${office.role}, not PATTARA`);
  }

  let created = 0;
  let updated = 0;

  for (const [assetTag, title, category, condition, maxLendingDays, purchasePrice, description] of SHELF) {
    const shape = {
      title,
      description,
      category,
      condition,
      maxLendingDays,
      purchasePrice,
      minLendingDays: 1,
      isRenewable: true,
      maxRenewals: 1,
      allowMeetup: true,
      meetupLocations: [PICKUP],
      images: [] as string[],
      tags: [] as string[],
      status: "AVAILABLE" as const,
      ownerId: office.id,
    };

    const existing = await prisma.lendingItem.findUnique({
      where: { assetTag },
      select: { id: true },
    });

    if (existing) {
      await prisma.lendingItem.update({ where: { id: existing.id }, data: shape });
      updated += 1;
    } else {
      await prisma.lendingItem.create({ data: { ...shape, assetTag } });
      created += 1;
    }
  }

  const byCategory = await prisma.lendingItem.groupBy({
    by: ["category"],
    where: { ownerId: office.id },
    _count: true,
  });

  console.log(`${created} created, ${updated} updated`);
  console.log("\nshelf by category");
  for (const row of byCategory.sort((a, b) => b._count - a._count)) {
    console.log("  " + row.category.padEnd(20) + row._count);
  }
  const total = await prisma.lendingItem.count({ where: { ownerId: office.id } });
  console.log("\n" + total + " items on the shelf, all AVAILABLE, no photos yet");
}

main()
  .then(() => process.exit(0))
  .catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
